export type MessageKey = keyof typeof en;

export function lang(): "en" | "ja" {
  if (settings.language !== "auto") return settings.language;
  return navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function t(k: MessageKey, vars: Record<string, string | number> = {}): string {
  let s = (lang() === "ja" ? ja : en)[k];
  for (const [name, v] of Object.entries(vars)) s = s.replace(`{${name}}`, String(v));
  return s;
}
